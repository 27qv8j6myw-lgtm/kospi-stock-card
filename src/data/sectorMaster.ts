export function stockNameFromMaster(code: string): string {
  const c = code.replace(/\D/g, '').padStart(6, '0')
  return NAMES[c] ?? c
}

/** 코어 종목명 — 없으면 null (코드 폴백 금지) */
export function screeningStockNameOrNull(code: string): string | null {
  const c = code.replace(/\D/g, '').padStart(6, '0')
  return NAMES[c] ?? null
}
