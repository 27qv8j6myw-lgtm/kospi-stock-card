/**
 * 보유 진단 섹션 뼈대 — 종목카드와 같은 뼈대 위에 보유 전용 섹션을 얹는다.
 * @param {{ isProfit: boolean, avgPrice: number, weightPct: number }} ctx
 */
export function holdingAnalysisSections({ isProfit, avgPrice, weightPct }) {
  const avg = avgPrice > 0 ? `${avgPrice.toLocaleString('ko-KR')}원` : '평단'
  const weight = `${weightPct.toFixed(0)}%`
  const bandGuide = isProfit
    ? '목표가 여력, 익절 비중, 트레일링 손절선'
    : '손절 기준, 추가매수(물타기) 적정성, 반등 시나리오'

  return `## [결론] 추가매수 / 홀딩 / 일부익절 / 손절 중 하나 + 한 줄 요약
## [지표] 핵심 데이터 (표 권장: 현재가와 평단 ${avg} 대비 수익률, PER/PBR, 외국인·기관 수급, 52주 위치, 컨센서스)
${SECTION_ISSUES}
## [${isProfit ? '수익' : '손실'} 구간 전략] ${bandGuide} — 평단 ${avg}, 비중 ${weight} 기준으로 판단
## [시나리오별 액션] 추가매수·익절·손절 각각의 발동 가격(원화)과 실행 비중
${SECTION_RISK}`
}

/**
 * 관리자(fable) 심층 모드 지침. 형식의 간결함보다 추론의 깊이를 우선한다.
 * @param {string[]} [axes] 이 분석에서 파고들 후보 축
 */
export function deepAnalysisRules(axes = []) {
  const axisLines =
    axes.length > 0
      ? `\n  아래 중 유의미한 축을 골라 깊게 다룬다 (전부 나열할 필요 없음):\n${axes
          .map((a) => `  · ${a}`)
          .join('\n')}`
      : ''

  return `[심층 분석 모드 — 최우선 지침]
이 요청은 전문 투자자를 위한 심층 분석이다. 형식의 간결함보다 추론의 깊이를 우선한다.

- 각 섹션에서 결론만 제시하지 말고 "왜 그런가"의 인과를 근거와 함께 논증한다.
  분량을 줄이려고 근거를 생략하지 않는다.
- [심층 통찰] 에는 표면 요약이 아니라 다른 곳에서 보기 어려운 해석을 담는다.${axisLines}
- 데이터가 없는 축은 억지로 채우지 말고, 무엇을 더 확인해야 하는지 밝힌다.`
}

